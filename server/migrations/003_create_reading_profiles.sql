CREATE TABLE reading_profiles (
  user_id INTEGER PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
  font_family VARCHAR(30) NOT NULL DEFAULT 'sans',
  font_size INTEGER NOT NULL DEFAULT 18 CHECK (font_size BETWEEN 14 AND 40),
  line_height DOUBLE PRECISION NOT NULL DEFAULT 1.6 CHECK (line_height BETWEEN 1.2 AND 2.5),
  letter_spacing DOUBLE PRECISION NOT NULL DEFAULT 0 CHECK (letter_spacing BETWEEN 0 AND 0.3),
  column_width INTEGER NOT NULL DEFAULT 60 CHECK (column_width BETWEEN 30 AND 100),
  background VARCHAR(20) NOT NULL DEFAULT 'putih',
  line_focus BOOLEAN NOT NULL DEFAULT FALSE,
  syllable_split BOOLEAN NOT NULL DEFAULT FALSE,
  tts_rate DOUBLE PRECISION NOT NULL DEFAULT 1 CHECK (tts_rate BETWEEN 0.5 AND 2),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);